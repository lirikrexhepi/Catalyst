import { launch, openDesktop } from './desktop.mjs'

const browser = await launch()
const { page } = await openDesktop(browser, { width: 1440, height: 900, scale: 1, storage: { 'composer:wallpaper': 'builtin-4' } })
await page.waitForTimeout(5500)
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.keyboard.press('Control+ArrowUp')
await page.waitForTimeout(300)
await page.keyboard.press('Control+ArrowUp')
await page.waitForTimeout(1500)
await page.screenshot({ path: '../scratch/d6-orch.png' })
await page.keyboard.press('Control+ArrowDown')
await page.keyboard.press('Control+ArrowDown')
await page.waitForTimeout(900)
await page.mouse.click(440, 849)
await page.waitForTimeout(900)
await page.screenshot({ path: '../scratch/d6-models.png' })
await page.keyboard.press('Escape')
await page.mouse.click(700, 700)
await page.waitForTimeout(500)
await page.mouse.move(829, 30)
await page.waitForTimeout(1000)
await page.screenshot({ path: '../scratch/d6-usage.png' })
await page.mouse.click(829, 30)
await page.waitForTimeout(1000)
await page.screenshot({ path: '../scratch/d6-usage-click.png' })
await browser.close()

